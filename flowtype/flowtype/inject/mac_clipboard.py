"""macOS pasteboard (pyobjc). Every item and every type on it is saved and restored as raw data. Our text is
marked transient (nspasteboard.org convention) so clipboard managers don't record it."""

from AppKit import NSPasteboard, NSPasteboardItem, NSPasteboardTypeString

TRANSIENT = "org.nspasteboard.TransientType"
AUTOGENERATED = "org.nspasteboard.AutoGeneratedType"


class MacClipboard:
    def __init__(self):
        self._pb = NSPasteboard.generalPasteboard()

    def snapshot(self):
        items = []
        for item in self._pb.pasteboardItems() or []:
            items.append([(t, item.dataForType_(t)) for t in item.types()])
        return items

    def set_text(self, text: str) -> None:
        self._pb.clearContents()
        item = NSPasteboardItem.alloc().init()
        item.setString_forType_(text, NSPasteboardTypeString)
        item.setString_forType_("", TRANSIENT)
        item.setString_forType_("", AUTOGENERATED)
        self._pb.writeObjects_([item])

    def restore(self, snap) -> None:
        self._pb.clearContents()
        objs = []
        for types in snap:
            item = NSPasteboardItem.alloc().init()
            for t, data in types:
                if data is not None:
                    item.setData_forType_(data, t)
            objs.append(item)
        if objs:
            self._pb.writeObjects_(objs)

    def change_marker(self) -> int:
        return int(self._pb.changeCount())
